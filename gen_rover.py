#!/usr/bin/env python3
"""gen_rover.py -- PRISM encoding of the rover terrain MDP (the oracle side).

Independent of checker/edgecheck.c by construction (plan-review R3): it reads
only the map file and terrain_params.csv and writes PRISM-language text.

  gen_rover.py MAP PARAMS OUT.prism [--noblind]

Model (plan.md Def. 1'): image-space range-bearing grid, row 0 nearest.
Rover starts below row 0 at column C//2. Each step: steer L/S/R into
(row+1, col-1|col|col+1). Entering class t: sink_t -> stuck, slip_t ->
lands one further column outward (straight: split both ways), else target.
Rock -> collided; off the image sideways -> blind; row R -> through.
The arc is encoded with constants A1..AM in {0,1,2} (L,S,R) and a step
counter t: while t < M only the arc's steer is enabled; afterwards all three.
"""
import sys
from fractions import Fraction

def read_map(path):
    lines = open(path).read().split()
    R, C = int(lines[0]), int(lines[1])
    rows = lines[2:2 + R]
    assert len(rows) == R and all(len(r) == C for r in rows)
    return R, C, [rows[R - 1 - r] for r in range(R)]          # grid[r] with r=0 nearest

def read_params(path):
    P = {}
    for ln in open(path).read().splitlines()[1:]:
        if not ln.strip(): continue
        name, slip, sink = ln.split(",")[:3]
        P[name] = (Fraction(slip), Fraction(sink))
    return P

NAME = {"b": "bedrock", "o": "soil", "s": "sand", "u": "unknown"}

def main():
    mp, pp, out = sys.argv[1:4]; noblind = "--noblind" in sys.argv
    M = 3
    for a in sys.argv:
        if a.startswith("--M="): M = int(a[4:])
    R, C, g = read_map(mp); P = read_params(pp)
    # status: 0 driving, 1 collided, 2 blind, 3 stuck, 4 through
    def land(r, c):
        if r >= R: return ("st", 4)
        if c < 0 or c >= C: return ("st", 2)
        if g[r][c] == "r": return ("st", 1)
        return ("cell", r, c)
    def upd(dest, tnext):
        if dest[0] == "st": return f"(st'={dest[1]})"
        return f"(row'={dest[1]})&(col'={dest[2]})&(t'={tnext})"
    L = [f"// GENERATED by gen_rover.py from {mp} -- do not edit", "mdp", ""]
    L += [f"const int A{i+1};" for i in range(M)]
    L += ["", "module rover",
          f"  row : [-1..{R-1}] init -1;",
          f"  col : [0..{C-1}] init {C//2};",
          "  st  : [0..4] init 0;",
          f"  t   : [0..{max(M, 1)}] init 0;"]  # PRISM rejects [0..0]
    for r in range(-1, R):
        for c in range(C):
            if r == -1 and c != C // 2: continue
            if r >= 0 and g[r][c] == "r": continue                 # unreachable as a position
            for d, act in ((-1, "go_l"), (0, "go_s"), (1, "go_r")):  # "S" is a PRISM keyword
                code = d + 1
                guard_arc = " | ".join([f"(t={i} & A{i+1}={code})" for i in range(M)] + [f"t={M}"])
                tn = f"min(t+1,{M})"
                tr, tc = r + 1, c + d
                base = land(tr, tc)
                if base[0] == "st":
                    rhs = upd(base, tn)
                else:
                    slip, sink = P[NAME[g[tr][tc]]]
                    ok = 1 - slip - sink
                    br = []
                    if ok > 0: br.append((ok, upd(base, tn)))
                    if sink > 0: br.append((sink, "(st'=3)"))
                    if slip > 0:
                        if d != 0: br.append((slip, upd(land(tr, tc + d), tn)))
                        else:
                            br.append((slip / 2, upd(land(tr, tc - 1), tn)))
                            br.append((slip / 2, upd(land(tr, tc + 1), tn)))
                    rhs = " + ".join(f"{p.numerator}/{p.denominator} : {u}" for p, u in br)
                L.append(f"  [{act}] st=0 & row={r} & col={c} & ({guard_arc}) -> {rhs};")
    L += ["  [stop] st>0 -> true;", "endmodule", "",
          'label "collided" = st=1;', 'label "blind" = st=2;', 'label "stuck" = st=3;',
          'label "through" = st=4;',
          f'label "fail" = st=1 | st=3{"" if noblind else " | st=2"};', ""]
    open(out, "w").write("\n".join(L))

if __name__ == "__main__":
    main()
