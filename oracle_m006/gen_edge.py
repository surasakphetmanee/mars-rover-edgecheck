#!/usr/bin/env python3
"""M006-EDGECHECKER — AEB loop with edge-AI, environment, attacker and monitor.

Rebuild after the v1 dead end (NOTES.md). Three components as the mission asks.

  EDGE-AI      brakes iff perceived gap <= stopping distance for the current
               speed; errs with probability eps and does the opposite.
  ENVIRONMENT  gap d (0..D), speed v (0..V). Each step the environment chooses
               NONDETERMINISTICALLY whether the obstacle closes one extra cell.
               It is player 2, so MDP maxima are worst-case over adversity.
  ATTACKER     spends from budget b to spoof the sensor upward by SPOOF cells,
               choosing WHEN. In the SMG arm it also owns the environment
               choice, which is the conservative reading.

  MONITOR      memory budget m = suspicion threshold. Suspicion rises when the
               sensor moves implausibly (perceived gap grew while closing) OR
               the controller violates the safety envelope (failed to brake
               when the envelope demanded it). At m it LATCHES to the fallback.
               Larger m needs more evidence, so it latches later.

  FALLBACK     reads the SAME sensor, so a spoof fools it too; but it is
               DETERMINISTIC, so unlike the AI it never brakes by accident.
               Latching under attack can therefore be worse than not latching.
               This is the mechanism the mission pre-registers as PR4.

  DEFENDER     player 1 in the SMG, spends a check budget c: monitoring a step
               costs one unit. The mission's "monitor placement under a compute
               budget", expressed at runtime.

Braking sheds one speed level per step, so stopping from v covers v(v+1)/2
cells; with the environment closing up to one extra cell per braking step the
worst case is v(v+1)/2 + v. Both controllers brake against that.
"""
from __future__ import annotations

import sys
from pathlib import Path

D, V = 16, 5
SPOOF = 5
D0, V0 = 15, 4
# AI_SLACK must be > 0. At 0 the AI brakes at exactly the worst-case-safe
# distance, so a single error is unrecoverable and the monitor provably cannot
# change the outcome -- which is what the first sweep measured (a curve flat in
# m to 16 digits). With margin, one error is survivable and an early latch to
# the much more conservative fallback genuinely recovers.
AI_SLACK, FB_SLACK = 2, 5


def stop_dist(expr_v: str) -> str:
    """Worst-case cells needed to stop from speed v: v(v+1)/2 + v."""
    return f"(({expr_v}*({expr_v}+1))/2 + {expr_v})"


def build(kind: str, e: int, den: int, B: int, C: int, M: int) -> str:
    smg = kind == "smg"
    PG = f"min({D}, d + sp*{SPOOF})"          # perceived gap
    ENV = stop_dist("v")
    ai_brake = f"({PG} <= {ENV} + {AI_SLACK})"
    fb_brake = f"({PG} <= {ENV} + {FB_SLACK})"
    # monitor evidence: implausible sensor step, or the controller left the envelope
    implausible = f"({PG} > pprev)"
    violation = f"({PG} <= {ENV} + {FB_SLACK} & bk=0)"
    evidence = f"({implausible} | {violation})"

    L = [f"// M006-EDGECHECKER AEB -- {kind}, eps={e}/{den}, b={B}, c={C}, m={M}",
         f"// D={D} V={V} SPOOF={SPOOF} init d={D0} v={V0} "
         f"AI_SLACK={AI_SLACK} FB_SLACK={FB_SLACK}",
         "// GENERATED by gen_edge.py -- do not edit by hand.", kind, ""]

    if smg:
        # PRISM-games rejects an action listed in a player block that no
        # command defines, so [check] is only declared when m > 0 emits it.
        dact = "[check], [skip]" if M > 0 else "[skip]"
        aact = "[spoof], [quiet], [env0], [env1]" if B > 0 else "[quiet], [env0], [env1]"
        L += [f"player defender {dact} endplayer",
              f"player attacker {aact} endplayer", ""]

    L += ["module aeb",
          f"  d  : [0..{D}] init {D0};",
          f"  v  : [0..{V}] init {V0};"]
    if B > 0:
        L.append(f"  bl : [0..{B}] init {B};")
    L += [f"  cl : [0..{C}] init {C};",
          f"  s  : [0..{max(M,1)}] init 0;",
          f"  pprev : [0..{D}] init {D0};",
          "  sp : [0..1] init 0;",
          "  bk : [0..1] init 0;      // this step's braking decision",
          "  lat: [0..1] init 0;",
          "  ph : [0..3] init 0;      // 0 attacker 1 defender 2 control 3 environment",
          "  w  : [0..2] init 0;      // 0 running 1 unsafe 2 stopped safely",
          ""]

    # phase 0 -- attacker
    L.append("  // phase 0 -- attacker chooses when to spend spoof budget")
    if B > 0:
        L.append("  [spoof] w=0 & ph=0 & bl>0 -> (sp'=1)&(bl'=bl-1)&(ph'=1);")
    L.append("  [quiet] w=0 & ph=0 -> (sp'=0)&(ph'=1);")
    L.append("")

    # phase 1 -- controller decides FIRST (needed for the envelope check), then
    # the defender may check. Implemented by deciding bk here.
    L.append("  // phase 1 -- the controller commits its action. The AI errs with")
    L.append("  //            probability eps; the latched fallback is deterministic.")
    for latched, brake_expr in ((1, fb_brake), (0, ai_brake)):
        if latched:
            L.append(f"  [ctl] w=0 & ph=1 & lat=1 & {brake_expr} -> (bk'=1)&(ph'=2);")
            L.append(f"  [ctl] w=0 & ph=1 & lat=1 & !({brake_expr}) -> (bk'=0)&(ph'=2);")
        else:
            for want, g in ((1, brake_expr), (0, f"!({brake_expr})")):
                other = 1 - want
                if e == 0:
                    L.append(f"  [ctl] w=0 & ph=1 & lat=0 & {g} -> (bk'={want})&(ph'=2);")
                else:
                    L.append(f"  [ctl] w=0 & ph=1 & lat=0 & {g} -> "
                             f"{den-e}/{den} : (bk'={want})&(ph'=2) + "
                             f"{e}/{den} : (bk'={other})&(ph'=2);")
    L.append("")

    # phase 2 -- defender check
    L.append("  // phase 2 -- defender spends a check. Evidence is an implausible")
    L.append("  //            sensor step OR a safety-envelope violation.")
    if M > 0:
        # On latching the monitor INTERCEPTS this step's action rather than
        # letting it actuate and taking over next step. The seed specifies
        # "falling back to a rule-based controller on violation", which is an
        # intercept; the first version let the offending action execute and the
        # MDP curve was consequently flat in m to 16 digits, because an error
        # already actuated cannot be recovered inside the AI's margin.
        L.append(f"  [check] w=0 & ph=2 & cl>0 & lat=0 & {evidence} & s+1>={M} ->"
                 f" (cl'=cl-1)&(s'={M})&(lat'=1)"
                 f"&(bk'= {fb_brake} ? 1 : 0)&(ph'=3);")
        L.append(f"  [check] w=0 & ph=2 & cl>0 & lat=0 & {evidence} & s+1<{M} ->"
                 " (cl'=cl-1)&(s'=s+1)&(ph'=3);")
        L.append(f"  [check] w=0 & ph=2 & cl>0 & lat=0 & !({evidence}) ->"
                 " (cl'=cl-1)&(s'=max(0,s-1))&(ph'=3);")
        L.append("  [check] w=0 & ph=2 & cl>0 & lat=1 -> (cl'=cl-1)&(ph'=3);")
    # In the MDP arm every nondeterministic choice is resolved by the SAME
    # maximiser, so leaving [skip] free would let Pmax switch the monitor OFF
    # and the curve would be flat in m -- which is exactly what the previous
    # sweep measured. The defender's policy is therefore FIXED in the MDP arm
    # (always check while budget remains) and only the environment is
    # nondeterministic. In the SMG arm [skip] stays a real defender choice.
    if smg or M == 0:
        L.append("  [skip]  w=0 & ph=2 -> (ph'=3);")
    else:
        L.append("  [skip]  w=0 & ph=2 & (cl=0 | lat=1) -> (ph'=3);")
    L.append("")

    # phase 3 -- environment adversity (nondeterministic) + physics
    L.append("  // phase 3 -- the environment chooses whether the obstacle closes")
    L.append("  //            one extra cell. Nondeterministic: player 2 owns it.")
    for extra in (0, 1):
        nv = "(bk=1 ? max(0,v-1) : v)"
        nd = f"max(0, d - {nv} - {extra})"
        unsafe = f"(({nd}=0) & ({nv}>0))"
        safe = f"({nv}=0)"
        L.append(f"  [env{extra}] w=0 & ph=3 -> (d'={nd})&(v'={nv})&(pprev'={PG})"
                 f"&(sp'=0)&(bk'=0)&(ph'=0)"
                 f"&(w'= {unsafe} ? 1 : ({safe} ? 2 : 0));")
    L.append("")
    L += ["  // absorbing", "  [done] w>0 -> true;", "endmodule", "",
          'label "unsafe"  = w=1;',
          'label "safe"    = w=2;',
          'label "done"    = w>0;',
          'label "latched" = lat=1;', "",
          'rewards "time"', "  [env0] true : 1;", "  [env1] true : 1;",
          "endrewards", ""]
    return "\n".join(L) + "\n"


def cell_id(kind, e, B, C, M):
    return f"aeb_{kind}_e{e:02d}_b{B}_c{C}_m{M}"


def main():
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "models")
    out.mkdir(parents=True, exist_ok=True)
    DEN, C, n = 100, 3, 0
    for kind, Bs in (("mdp", [0]), ("smg", [1, 2, 3])):
        for e in (0, 5, 10, 20):
            for B in Bs:
                for M in (0, 1, 2, 3, 4):
                    (out / f"{cell_id(kind,e,B,C,M)}.prism").write_text(
                        build(kind, e, DEN, B, C, M))
                    n += 1
    print(f"wrote {n} models")


if __name__ == "__main__":
    main()
