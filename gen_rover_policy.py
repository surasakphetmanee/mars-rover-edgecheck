#!/usr/bin/env python3
"""gen_rover_policy.py -- D5: PRISM DTMC of the terrain model with the arc's three steers
(constants A1..A3) followed by a fixed policy (steer per cell, from a policy file) for the
remaining steps. Same transition rules as gen_rover.py (copied, not imported, so the
oracle stays text-only). Policy file: R lines (far row first, as the map) of L/S/R chars.

  gen_rover_policy.py MAP PARAMS POLICY OUT.prism
"""
import sys
from fractions import Fraction
from gen_rover import read_map, read_params, NAME

def main():
    mp, pp, pol, out = sys.argv[1:5]; M = 3
    R, C, g = read_map(mp); P = read_params(pp)
    prow = open(pol).read().split(); assert len(prow) == R
    policy = [prow[R - 1 - r] for r in range(R)]                     # policy[r][c], r=0 nearest
    def land(r, c):
        if r >= R: return ("st", 4)
        if c < 0 or c >= C: return ("st", 2)
        if g[r][c] == "r": return ("st", 1)
        return ("cell", r, c)
    def upd(dest, tnext):
        if dest[0] == "st": return f"(st'={dest[1]})"
        return f"(row'={dest[1]})&(col'={dest[2]})&(t'={tnext})"
    L = [f"// GENERATED by gen_rover_policy.py from {mp} + {pol} -- do not edit", "dtmc", ""]
    L += [f"const int A{i+1};" for i in range(M)]
    L += ["", "module rover", f"  row : [-1..{R-1}] init -1;", f"  col : [0..{C-1}] init {C//2};",
          "  st  : [0..4] init 0;", f"  t   : [0..{M}] init 0;"]
    for r in range(-1, R):
        for c in range(C):
            if r == -1 and c != C // 2: continue
            if r >= 0 and g[r][c] == "r": continue
            for d, act in ((-1, "go_l"), (0, "go_s"), (1, "go_r")):
                code = d + 1
                guards = [f"(t={i} & A{i+1}={code})" for i in range(M)]
                if r >= 0 and "LSR"[code] == policy[r][c]: guards.append(f"t={M}")
                tn = f"min(t+1,{M})"; tr, tc = r + 1, c + d; base = land(tr, tc)
                if base[0] == "st": rhs = upd(base, tn)
                else:
                    slip, sink = P[NAME[g[tr][tc]]]; ok = 1 - slip - sink; br = []
                    if ok > 0: br.append((ok, upd(base, tn)))
                    if sink > 0: br.append((sink, "(st'=3)"))
                    if slip > 0:
                        if d != 0: br.append((slip, upd(land(tr, tc + d), tn)))
                        else: br += [(slip / 2, upd(land(tr, tc - 1), tn)), (slip / 2, upd(land(tr, tc + 1), tn))]
                    rhs = " + ".join(f"{p.numerator}/{p.denominator} : {u}" for p, u in br)
                L.append(f"  [{act}] st=0 & row={r} & col={c} & ({' | '.join(guards)}) -> {rhs};")
    L += ["  [stop] st>0 -> true;", "endmodule", "", 'label "fail" = st=1 | st=3 | st=2;', ""]
    open(out, "w").write("\n".join(L))

if __name__ == "__main__":
    main()
